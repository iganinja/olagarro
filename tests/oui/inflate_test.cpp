TEST(OuiInflateTests, ReadsABlockOfFixedCodes)
{
    EXPECT_EQ(oui::inflate_gzip(fixed_block), "hello hello hello hello");
}

TEST(OuiInflateTests, ReadsAStoredBlock)
{
    EXPECT_EQ(oui::inflate_gzip(stored_block), random_bytes);
}

TEST(OuiInflateTests, EmbeddedFilesComeBackAsTheyWere)
{
    // Text and fonts, large enough for blocks of codes of their own: what CMake compressed comes back whole.
    const std::filesystem::path source{OLAGARRO_SOURCE_DIR};
    const auto embedded{embedded_inflate_test_files()};
    ASSERT_EQ(embedded.size(), 2u);
    EXPECT_EQ(embedded[0], file_text(source / "doc/oui_layout.md"));
    EXPECT_EQ(embedded[1], file_text(source / "oui/fonts/spleen_16x32.psfu"));
}

TEST(OuiInflateTests, SaysWhenWhatItReadsIsBroken)
{
    auto changed{fixed_block};
    // A byte of the text, so the check of its CRC fails.
    changed[12] ^= 0x01;
    EXPECT_THROW(static_cast<void>(oui::inflate_gzip(changed)), std::runtime_error);
    EXPECT_THROW(static_cast<void>(oui::inflate_gzip(fixed_block.substr(0, 15))), std::runtime_error);
    EXPECT_THROW(static_cast<void>(oui::inflate_gzip("not gzip at all")), std::runtime_error);
}
