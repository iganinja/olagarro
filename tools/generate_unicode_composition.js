// Makes oui/src/unicode_composition.h: what a Latin letter and a combining diacritic after it make together, as one
// precomposed (NFC) character. It serves dead keys on the Windows console, and combining marks typed or kept as NFD.
// The compositions come from the JavaScript engine's own Unicode tables, through String.prototype.normalize.
//
// Run with oui_run from the repository: `oui_run tools/generate_unicode_composition.js`.

const output = "oui/src/unicode_composition.h";

const diacritics = [
    [0x0300, "grave"],
    [0x0301, "acute"],
    [0x0302, "circumflex"],
    [0x0303, "tilde"],
    [0x0304, "macron"],
    [0x0306, "breve"],
    [0x0307, "dot above"],
    [0x0308, "diaeresis"],
    [0x030a, "ring above"],
    [0x030b, "double acute"],
    [0x030c, "caron"],
    [0x0327, "cedilla"],
    [0x0328, "ogonek"],
];

const letters = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ";
const hex = (codepoint) => codepoint.toString(16).toUpperCase().padStart(4, "0");

const header = `#pragma once

// Generated by tools/generate_unicode_composition.js. Do not edit by hand.

#include <optional>

namespace olagarro::oui
{

struct Composition
{
    char32_t base;
    char32_t diacritic;
    char32_t result;
};

namespace
{

constexpr Composition composition_table[] = {
`;

const footer = `};

} // namespace

[[nodiscard]] inline bool is_diacritic(char32_t codepoint)
{
    return codepoint >= U'\\u0300' && codepoint <= U'\\u036F';
}

[[nodiscard]] inline std::optional<char32_t> compose(char32_t base, char32_t diacritic)
{
    for(const auto& entry : composition_table)
    {
        if(entry.base == base && entry.diacritic == diacritic)
        {
            return entry.result;
        }
    }
    return std::nullopt;
}

} // namespace olagarro::oui
`;

const lines = [];
for (const [diacritic, name] of diacritics) {
    const entries = [];
    for (const base of letters) {
        const composed = (base + String.fromCodePoint(diacritic)).normalize("NFC");
        if ([...composed].length === 1) {
            entries.push(`    {U'${base}', U'\\u${hex(diacritic)}', U'\\u${hex(composed.codePointAt(0))}'}, // ${composed}`);
        }
    }
    if (entries.length > 0) {
        lines.push(`    // ${name[0].toUpperCase()}${name.slice(1)} U+${hex(diacritic)}`, ...entries);
    }
}
if (!oui.writeFile(output, header + lines.join("\n") + "\n" + footer)) {
    console.log(`Could not write ${output}`);
    oui.exit(1);
}
